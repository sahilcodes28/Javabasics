package B_operators;

public class A_ArithmeticOperators {
public static void main(String[] args) {

    int a = 68;
    int b = 4;

    System.out.println("Addiition: " + (a + b));              //addition
    System.out.println("Subtraction: " + (a - b));           //subtraction
    System.out.println("Multiplication: " + (a * b));       //multiplication
    System.out.println("Division : " + (a / b));           //division
    System.out.println("Remainder: " + (a % b));          //Modulus
}
}